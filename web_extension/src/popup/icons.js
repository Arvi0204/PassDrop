const NS = 'http://www.w3.org/2000/svg';

function svgFrom(markup, attrs) {
  const doc = new DOMParser().parseFromString(`<svg xmlns="${NS}" ${attrs}>${markup}</svg>`, 'image/svg+xml');
  return document.importNode(doc.documentElement, true);
}

/** A 24x24 line icon; size it with a class such as "w-4 h-4". */
export function icon(name, className = 'w-4 h-4') {
  const svg = svgFrom(
    PATHS[name],
    'viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"'
  );
  svg.setAttribute('class', className);
  return svg;
}

/** The PassDrop mark: two overlapping drops (same artwork as the web app). */
export function logo(size = 28) {
  const img = document.createElement('img');
  img.src = logoUrl;
  img.alt = '';
  img.width = img.height = size;
  img.className = 'shrink-0';
  return img;
}

/** The water drop that carries characters into a new password. */
export function dropMark(width = 16, height = 20) {
  const img = document.createElement('img');
  img.src = dropUrl;
  img.alt = '';
  img.width = width;
  img.height = height;
  return img;
}
